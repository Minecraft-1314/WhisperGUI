    FALLBACK_LANG = "en"

    @classmethod
    def get(cls, key, lang, **kwargs):
        table = cls.translations.get(lang) or cls.translations[cls.FALLBACK_LANG]
        text = table.get(key)
        if text is None:
            text = cls.translations[cls.FALLBACK_LANG].get(key, key)
        if not kwargs:
            return text
        return text.format(**kwargs)
